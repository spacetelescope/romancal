def angle_to_vector(alpha, delta):
    """
    Convert spherical angles to unit vector.

    Parameters
    ----------
    alpha, delta : float
        Spherical angles in radians.

    Returns
    -------
    v : [float, float, float]
        Unit vector.
    """
    v0 = cos(delta) * cos(alpha)
    v1 = cos(delta) * sin(alpha)
    v2 = sin(delta)

    return [v0, v1, v2]


def calc_position_angle(point, ref):
    """
    Calculate position angle from reference to point.

        tan(pa) = cos(dec_r) * sin(ra_r - ra_p) / (sin(dec_r)cos(dec_p) - cos(dec_r)sin(dec_p)cos(ra_r-ra_p))

    where::

        pa : position angle
        *_r : reference
        *_p : point

    Typically the reference is the V3 RA/DEC and point is the object RA/DEC.

    Parameters
    ----------
    point : WCSRef
        The POINT wcs parameters, in radians.

    ref : WCSRef
        The TARGET wcs parameters, in radians.

    Returns
    -------
    point_pa : float
      The POINT position angle, in radians
    """
    y = cos(ref.dec) * sin(ref.ra - point.ra)
    x = sin(ref.dec) * cos(point.dec) - cos(ref.dec) * sin(point.dec) * cos(
        ref.ra - point.ra
    )
    point_pa = np.arctan2(y, x)
    if point_pa < 0:
        point_pa += PI2
    if point_pa >= PI2:
        point_pa -= PI2

    logger.debug("Given reference: %s, point: %s, then PA: %s", ref, point, point_pa)
    return point_pa


def fetch_references(t_pars):
    """Fetch and load reference files.

    Fetch and load the necessary reference files.
    Currently this includes the BAM and DISTORTION references.

    If the reference file paths are not already defined, the references
    are fetched from CRDS and the TransformParameters is updated.
    The parameters used for fetching will be found in TransformParameters.crds_pars

    Parameters
    ----------
    t_pars : TransformParameters
        References are located locally or fetched from CRDS. The path information is
        updated in place.

        If fetching is needed, `t_pars.crds_pars` is used for the fetching.
    """
    reftypes = {'bam': 'bam_ref',
                'distortion': 'distortion_ref'}
    reftypes_to_fetch = []
    for reftype in reftypes:
        if not getattr(t_pars, reftypes[reftype], None):
            reftypes_to_fetch.append(reftype)
    refpaths = dict()
    if reftypes_to_fetch:
        refpaths = getreferences(t_pars.crds_pars, reftypes_to_fetch, observatory='roman')
    for reftype in refpaths:
        setattr(t_pars, reftypes[reftype], refpaths[reftype])
    for reftype in reftypes:
        logger.info('%s reference: %s', reftype.upper(), getattr(t_pars, reftypes[reftype]))


def hv_to_fgs(aperture_name, h, v, siaf_path=None):
    """Convert HV frame to FGS frame

    Source document: Innerspace Confluence: "Quaternion Transforms for Coarse Pointing WCS"
    from the section "Derive M_fgstogsapp". The coordinates systems are based on
    Eq. 7 of "Roman-STScI-000416 (Roman SOC FGS Algorithms)"

    Parameters
    ----------
    aperture_name : str
        The aperture in which the guide star is located.

    h, v : float, float
        The commanded coordinates in the HV frame.
        Units are in pixels.

    siaf_path : str
        The folder where the SIAF xml information resides.

    Returns
    -------
    fgs_x, fgs_y : float, float
        The coordinates in the FGS reference frame in arcsec.
    """
    siaf = siaf_lib.open_siaf(basepath=siaf_path)
    aper = siaf[aperture_name]
    aper_wfi_cen = siaf["WFI_CEN"]

    # Location of GS. This is from Eqn. 7 of Roman-STScI-000416 (Roman SOC FGS Algorithms)
    x, y = h + aper.XSciRef, aper.YSciRef - v
    v2, v3 = aper.sci_to_tel(x, y)  # Convert sci to tel coords using pysiaf

    # Convert tel to WFI_CEN idl coords using pysiaf.
    # The only difference between FGS and WFI_CEN coordinates is that the Y-axis is flipped
    x_wc, y_wc = aper_wfi_cen.tel_to_idl(v2, v3)
    x_fgs, y_fgs = x_wc, -y_wc

    return x_fgs, y_fgs


def mk_crds_pars(obstime=None, detector='WFI01', optical_element='F062'):
    """Create CRDS parameters from the transformation parameters.

    Parameters
    ----------
    obstime : astropy.time.Time or None
        Time of observation. If undefined, current time is used.

    detector : str
        The detector to use. Form should be "WFIXX"
        where "XX" is the zero-padded number of the detector.

    optical_element : str
        The optical element to use.

    Returns
    -------
    crds_pars : dict
        Dictionary of parameters needed for CRDS reference file retrieval.
    """
    if not obstime:
        obstime = Time.now()

    pars = {
        'ROMAN.META.INSTRUMENT.DETECTOR': detector,
        'ROMAN.META.INSTRUMENT.NAME': detector[:3],
        'ROMAN.META.INSTRUMENT.OPTICAL_ELEMENT': optical_element,
        'ROMAN.META.EXPOSURE.START_TIME': obstime.isot,
    }
    return pars


def update_meta(model, t_pars, wcs_meta, quality):
    """Update model's meta info with the given pointing.

    The following meta are update:
    - meta.guide_star.hv_position
    - meta.pointing.dec_v1
    - meta.pointing.pa_aperture
    - meta.pointing.pa_v3
    - meta.pointing.quaternion
    - meta.pointing.ra_v1
    - meta.pointing.target_dec
    - meta.pointing.target_ra
    - meta.wcsinfo.dec_ref
    - meta.wcsinfo.ra_ref
    - meta.wcsinfo.roll_ref
    - meta.wcsinfo.s_region

    Parameters
    ----------
    model : `~roman.datamodels.DataModel`
        The model to update. Updates are done in-place.

    t_pars : `TransformParameters`
        The transformation parameters. Parameters are updated during processing.

    wcs_meta : dict
        The major meta blocks with the update information.
        This is the dict returned from `calc_wcs`

    quality : str
        Indicator of the success of the pointing determination.
    """
    model.meta.pointing.pointing_engineering_source = quality

    for section in wcs_meta:
        section_meta = getattr(model.meta, section)
        for k, v in wcs_meta[section].items():
            setattr(section_meta, k, v)

    model.meta.ref_file.bam = Path(t_pars.bam_ref).name
    model.meta.ref_file.distortion = Path(t_pars.distortion_ref).name


def vector_to_angle(v):
    """
    Return tuple of spherical angles from unit direction Vector.

    The Direction Cosine Matrix (DCM) that provides the transformation of a
    unit pointing vector defined in inertial frame (ECI J2000) coordinates to a
    unit vector defined in the science aperture Ideal frame coordinates is
    defined as.

    Parameters
    ----------
    v : [v0, v1, v2]
        Direction vector.

    Returns
    -------
    alpha, delta : float, float
        The spherical angles, in radians.
    """
    alpha = np.arctan2(v[1], v[0])
    delta = np.arcsin(v[2])
    if alpha < 0.0:
        alpha += 2.0 * np.pi
    return alpha, delta
