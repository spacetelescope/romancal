def fetch_references(t_pars):
    """Fetch and load reference files.

    Fetch and load the necessary reference files.
    Currently this includes the BAM and DISTORTION references.

    If the reference file paths are not already defined, the references
    are fetched from CRDS and the TransformParameters is updated.
    The parameters used for fetching will be found in TransformParameters.crds_pars

    Parameters
    ----------
    t_pars : TransformParameters
        References are located locally or fetched from CRDS. The path information is
        updated in place.

        If fetching is needed, `t_pars.crds_pars` is used for the fetching.
    """
    reftypes = {"bam": "bam_ref", "distortion": "distortion_ref"}
    reftypes_to_fetch = []
    for reftype in reftypes:
        if not getattr(t_pars, reftypes[reftype], None):
            reftypes_to_fetch.append(reftype)
    refpaths = dict()
    if reftypes_to_fetch:
        refpaths = getreferences(
            t_pars.crds_pars, reftypes_to_fetch, observatory="roman"
        )
    for reftype in refpaths:
        setattr(t_pars, reftypes[reftype], refpaths[reftype])
    for reftype in reftypes:
        logger.info(
            "%s reference: %s", reftype.upper(), getattr(t_pars, reftypes[reftype])
        )


def mk_crds_pars(obstime=None, detector="WFI01", optical_element="F062"):
    """Create CRDS parameters from the transformation parameters.

    Parameters
    ----------
    obstime : astropy.time.Time or None
        Time of observation. If undefined, current time is used.

    detector : str
        The detector to use. Form should be "WFIXX"
        where "XX" is the zero-padded number of the detector.

    optical_element : str
        The optical element to use.

    Returns
    -------
    crds_pars : dict
        Dictionary of parameters needed for CRDS reference file retrieval.
    """
    if not obstime:
        obstime = Time.now()

    pars = {
        "ROMAN.META.INSTRUMENT.DETECTOR": detector,
        "ROMAN.META.INSTRUMENT.NAME": detector[:3],
        "ROMAN.META.INSTRUMENT.OPTICAL_ELEMENT": optical_element,
        "ROMAN.META.EXPOSURE.START_TIME": obstime.isot,
    }
    return pars


def update_meta(model, t_pars, wcs_meta, quality):
    """Update model's meta info with the given pointing.

    The following meta are update:
    - meta.guide_star.hv_position
    - meta.pointing.dec_v1
    - meta.pointing.pa_aperture
    - meta.pointing.pa_v3
    - meta.pointing.quaternion
    - meta.pointing.ra_v1
    - meta.pointing.target_dec
    - meta.pointing.target_ra
    - meta.wcsinfo.dec_ref
    - meta.wcsinfo.ra_ref
    - meta.wcsinfo.roll_ref
    - meta.wcsinfo.s_region

    Parameters
    ----------
    model : `~roman.datamodels.DataModel`
        The model to update. Updates are done in-place.

    t_pars : `TransformParameters`
        The transformation parameters. Parameters are updated during processing.

    wcs_meta : dict
        The major meta blocks with the update information.
        This is the dict returned from `calc_wcs`

    quality : str
        Indicator of the success of the pointing determination.
    """
    model.meta.pointing.pointing_engineering_source = quality

    for section in wcs_meta:
        section_meta = getattr(model.meta, section)
        for k, v in wcs_meta[section].items():
            setattr(section_meta, k, v)

    model.meta.ref_file.bam = Path(t_pars.bam_ref).name
    model.meta.ref_file.distortion = Path(t_pars.distortion_ref).name
